  // 학생용 — 신촌/홍대 저녁 + 금요일 종일 + 주말
  push('카페·음식점', { days:['MON','WED'], start:'17:30', end:'22:00' }, '신촌',   11500, { title:'브런치 카페 마감 스태프', company:'브런치하우스 온 신촌점' });
