/* ---------------------------------------------------------------------
 * 목데이터 생성기 — 시드 고정 난수로 매 실행 동일한 72건 생성
 * + 데모 시나리오(학생/직장인)용 공고 8건 의도 배치
 * -------------------------------------------------------------------*/
function seededRandom(seed) {
  let s = seed >>> 0;
  return function () {
    s = (s + 0x6D2B79F5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

